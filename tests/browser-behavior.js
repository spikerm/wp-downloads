    selection=[{id:1,filename:'manual.pdf'}];callback();assert.equal($('#rex-download-title').val(),'manual.pdf');
    selection=[{id:1,filename:'manual.pdf'},{id:2,filename:'firmware.zip'}];callback();assert.deepEqual(JSON.parse($('#rex-media-ids').val()),[1,2]);assert.match($('#rex-download-title').val(),/Bulkimport/);
