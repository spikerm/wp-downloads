    const mediaDom=new JSDOM('<input id="rex-edit-id" value="0"><input id="rex-use-filename" type="checkbox" checked><input id="rex-download-title"><input id="rex-media-id"><input id="rex-media-ids"><span id="rex-media-name"></span><button id="rex-media-select"></button><button id="rex-media-clear"></button>',{runScripts:'outside-only'});
    const mw=mediaDom.window;const $=jquery(mw);mw.jQuery=$;let selection;let callback;let configuration;
    mw.wp={media: options => {configuration=options;return {on:(event,fn)=>callback=fn,open(){},state:()=>({get:()=>({toJSON:()=>selection})})};}};
    mw.eval(source('media-selector.js'));mw.document.dispatchEvent(new mw.Event('DOMContentLoaded'));await tick();
